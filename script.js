const CATEGORIES = {
  "ЗАВТРАКИ": "🍳 Завтраки",
  "ПЕРВЫЕ БЛЮДА": "🍲 Первые блюда",
  "ВТОРЫЕ БЛЮДА": "🍖 Вторые блюда",
  "ДЕСЕРТЫ": "🍰 Десерты",
  "ПОЛДНИК": "🥤 Полдник",
  "УЖИН": "🍽️ Ужин"
};

let state = { view: "all", category: null, searchName: "", searchIng: "" };
let openCards = new Set();

function getUserRecipes() {
  try { return JSON.parse(localStorage.getItem("myRecipes") || "[]"); }
  catch (e) { return []; }
}
function saveUserRecipes(list) {
  localStorage.setItem("myRecipes", JSON.stringify(list));
}

function allRecipes() {
  const mine = getUserRecipes();
  const result = [];
  for (const cat in RECIPES) RECIPES[cat].forEach(r => result.push(Object.assign({}, r, {category: cat})));
  mine.forEach(r => result.push(Object.assign({}, r, {category: "МОИ РЕЦЕПТЫ"})));
  return result;
}

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function visibleRecipes() {
  let list = allRecipes();
  if (state.view === "mine") list = list.filter(r => r.category === "МОИ РЕЦЕПТЫ");
  if (state.view === "category" && state.category) list = list.filter(r => r.category === state.category);
  if (state.searchName) list = list.filter(r => r.name.toLowerCase().includes(state.searchName.toLowerCase()));
  if (state.searchIng) list = list.filter(r => Object.keys(r.ingredients).some(i => i.toLowerCase().includes(state.searchIng.toLowerCase())));
  return list;
}

function render() {
  const container = document.getElementById("recipe-list");
  const heading = document.getElementById("list-heading");
  let list = visibleRecipes();

  if (state.view === "category" && state.category) {
    heading.textContent = CATEGORIES[state.category] + " (" + list.length + ")";
  } else if (state.view === "mine") {
    heading.textContent = "✍️ Мои рецепты (" + list.length + ")";
  } else {
    heading.textContent = "📋 Все блюда (" + list.length + ")";
  }

  if (!list.length) {
    container.innerHTML = '<p class="empty">Ничего не найдено. Попробуйте другую категорию или измените запрос.</p>';
    return;
  }

  container.innerHTML = list.map(r => {
    const isOpen = openCards.has(r.id + "|" + r.name);
    const ings = Object.keys(r.ingredients).map(i => "• " + esc(i) + ": " + esc(r.ingredients[i])).join("\n");
    const steps = r.steps.map((s, i) => (i + 1) + ". " + esc(s)).join("\n");
    return '<div class="card' + (isOpen ? " open" : "") + '" data-key="' + esc(r.id + "|" + r.name) + '">' +
      '<div class="card-head"><span class="card-title">' + esc(r.name) + '</span>' +
      '<span class="card-meta">⏱ ' + esc(r.time) + ' · 🔥 ~' + r.calories + ' ккал · 👥 ' + r.servings + '</span></div>' +
      '<div class="card-body"><pre class="ings">' + ings + '</pre><pre class="steps">' + steps + '</pre></div>' +
      '<div class="card-actions"><button class="btn-toggle">' + (isOpen ? "▲ Свернуть" : "▼ Открыть рецепт") + '</button>' +
      '<button class="btn-dl">⬇ txt</button></div></div>';
  }).join("");

  container.querySelectorAll(".card").forEach(card => {
    const key = card.getAttribute("data-key");
    card.querySelector(".btn-toggle").addEventListener("click", () => {
      if (openCards.has(key)) openCards.delete(key); else openCards.add(key);
      render();
    });
    card.querySelector(".btn-dl").addEventListener("click", () => {
      const r = visibleRecipes().find(x => (x.id + "|" + x.name) === key);
      if (r) downloadRecipe(r);
    });
  });
}

function downloadRecipe(r) {
  let text = "РЕЦЕПТ: " + r.name + "\nВремя: " + r.time + "\nПорции: " + r.servings +
    "\nКалории: " + r.calories + " ккал\n\nИНГРЕДИЕНТЫ:\n";
  for (const i in r.ingredients) text += "- " + i + ": " + r.ingredients[i] + "\n";
  text += "\nПРИГОТОВЛЕНИЕ:\n";
  r.steps.forEach((s, i) => text += (i + 1) + ". " + s + "\n");
  const blob = new Blob([text], {type: "text/plain;charset=utf-8"});
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = r.name + ".txt";
  a.click();
  URL.revokeObjectURL(a.href);
}

function setView(view, category) {
  state.view = view;
  state.category = category || null;
  openCards.clear();
  document.querySelectorAll(".cat-btn").forEach(b => b.classList.remove("active"));
  const id = view === "all" ? "cat-all" : view === "mine" ? "cat-mine" : "cat-" + category;
  const btn = document.getElementById(id);
  if (btn) btn.classList.add("active");
  render();
}

function randomRecipe() {
  const list = visibleRecipes().length ? visibleRecipes() : allRecipes();
  const r = list[Math.floor(Math.random() * list.length)];
  const key = r.id + "|" + r.name;
  openCards.clear();
  openCards.add(key);
  render();
  setTimeout(() => {
    const card = document.querySelector('[data-key="' + CSS.escape(key) + '"]');
    if (card) card.scrollIntoView({behavior: "smooth", block: "center"});
  }, 60);
}

document.addEventListener("DOMContentLoaded", () => {
  const catsEl = document.getElementById("cats");
  catsEl.innerHTML = Object.keys(CATEGORIES).map(c =>
    '<button class="cat-btn" id="cat-' + c + '">' + CATEGORIES[c] + '</button>').join("");

  Object.keys(CATEGORIES).forEach(c => {
    document.getElementById("cat-" + c).addEventListener("click", () => setView("category", c));
  });
  document.getElementById("cat-all").addEventListener("click", () => setView("all"));
  document.getElementById("cat-mine").addEventListener("click", () => setView("mine"));
  document.getElementById("cat-random").addEventListener("click", randomRecipe);

  document.getElementById("search-name").addEventListener("input", e => {
    state.searchName = e.target.value.trim(); render();
  });
  document.getElementById("search-ing").addEventListener("input", e => {
    state.searchIng = e.target.value.trim(); render();
  });

  document.getElementById("add-form").addEventListener("submit", e => {
    e.preventDefault();
    const name = document.getElementById("f-name").value.trim();
    const time = document.getElementById("f-time").value.trim() || "не указано";
    const cal = parseInt(document.getElementById("f-cal").value, 10) || 0;
    const ings = document.getElementById("f-ings").value.split(",").map(s => s.trim()).filter(Boolean);
    const steps = document.getElementById("f-steps").value.split(".").map(s => s.trim()).filter(Boolean);
    if (!name || !ings.length || !steps.length) { alert("Заполните название, ингредиенты и шаги."); return; }
    const ingObj = {};
    ings.forEach(i => ingObj[i] = "по вкусу");
    const mine = getUserRecipes();
    mine.push({id: "user." + (mine.length + 1), name: name, time: time, servings: 1, calories: cal, ingredients: ingObj, steps: steps});
    saveUserRecipes(mine);
    e.target.reset();
    setView("mine");
  });

  document.getElementById("clear-mine").addEventListener("click", () => {
    if (confirm("Удалить все ваши рецепты?")) { saveUserRecipes([]); setView("mine"); }
  });

  render();
});
